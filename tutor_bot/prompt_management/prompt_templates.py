async def load_default_prompts(prompt_manager: PromptManager):
    """Загружает стандартные шаблоны промптов в базу данных, если они еще не существуют или если версия отличается."""
    print("Attempting to load default prompts into the database...")
    prompts_loaded_count = 0
    prompts_updated_count = 0
    prompts_skipped_count = 0

    # Подстановка констант агентов в строки шаблонов
    if OrchestratorAgent: # Проверка на случай если класс не импортирован (хотя он должен быть)
        # Ensure the key exists before trying to format
        if "orchestrator_intent_prompt_v2" in DEFAULT_PROMPT_TEMPLATES:
            try:
                DEFAULT_PROMPT_TEMPLATES["orchestrator_intent_prompt_v2"]["text"] = \
                    DEFAULT_PROMPT_TEMPLATES["orchestrator_intent_prompt_v2"]["text"].format(
                        OrchestratorAgent=OrchestratorAgent
                    )
            except KeyError as e:
                print(f"KeyError during formatting orchestrator_intent_prompt_v2: {e}. This might happen if a .format() placeholder is incorrect or an agent constant is missing.")


    for name, data in DEFAULT_PROMPT_TEMPLATES.items():
        text = data["text"]
        description = data.get("description")
        tags = data.get("tags", [])
        version = int(name.split('_v')[-1]) if '_v' in name else 1 # Простая логика извлечения версии из имени

        try:
            existing_prompt = await prompt_manager.get_prompt_model(name, version)
            if existing_prompt:
                if existing_prompt.text != text or existing_prompt.description != description:
                    # Если текст или описание изменились, можно обновить (или создать новую версию)
                    # Для простоты, если текст отличается, мы можем просто обновить его.
                    # В более сложной системе, возможно, стоило бы создавать новую версию.
                    await prompt_manager.update_prompt_text(name, version, text) # Это обновит и updated_at
                    # Также можно обновить description и tags, если PromptManager это поддерживает
                    print(f"Prompt '{name}' v{version} updated in DB.")
                    prompts_updated_count += 1
                else:
                    # print(f"Prompt '{name}' v{version} already exists and is up-to-date.")
                    prompts_skipped_count += 1
            else:
                await prompt_manager.create_prompt(name, text, description, tags, version, is_active=True)
                print(f"Prompt '{name}' v{version} created in DB and set to active.")
                prompts_loaded_count += 1
        except Exception as e:
            print(f"Error loading prompt '{name}' v{version}: {e}")

    total_processed = prompts_loaded_count + prompts_updated_count + prompts_skipped_count
    print(f"Default prompts loading complete. Total processed: {total_processed}. Loaded: {prompts_loaded_count}, Updated: {prompts_updated_count}, Skipped: {prompts_skipped_count}.")
